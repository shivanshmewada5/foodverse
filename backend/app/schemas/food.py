from typing import List, Optional, Dict, Any
from pydantic import BaseModel

class BoundingBox(BaseModel):
    x: float
    y: float
    width: float
    height: float

class DetectedIngredient(BaseModel):
    name: str
    category: str # e.g. Protein, Vegetable, Dairy, Grain, Spice
    confidence: float

class FoodItemDetection(BaseModel):
    name: str
    dish_category: str # e.g. Salad, Pasta, Curry, Dessert, Healthy Bowl
    confidence: float
    estimated_portion_grams: float
    bounding_box: Optional[BoundingBox] = None
    ingredients: List[DetectedIngredient] = []

class FoodRecognitionResult(BaseModel):
    title: str
    primary_dish: str
    all_detected_items: List[FoodItemDetection]
    total_items_count: int
    overall_confidence: float
    model_used: str # e.g. "FoodVerse VisionNet v2.4 + Multimodal Feature Extractor"
    processing_time_ms: float
    image_url: str
    analysis_id: Optional[int] = None
    created_at: str
    disclaimer: str = "AI detections are generated by computer vision heuristics and deep visual models. Confirm ingredients if you have severe allergies."
